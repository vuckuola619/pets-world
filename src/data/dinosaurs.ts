export const dinosaursAsAnimals: DinosaurAnimalEntry[] = dinosaurs.map((record) => {
  const realImg = REAL_DINO_IMAGES[record.slug];
  const illustration = createDinosaurIllustration(record);
  
  return {
    id: record.id,
    slug: record.slug,
    country: record.country,
    flag: '🦴',
    lat: record.lat,
    lng: record.lng,
    region: record.region,
    animal: record.commonName,
    scientificName: record.scientificName,
    emoji: emojiFor(record),
    classification: record.family === 'Not listed in PBDB' ? 'Dinosauria' : record.family,
    diet: titleCase(record.diet),
    conservationStatus: 'Extinct',
    indigenous: true,
    funFacts: [
      record.evidenceNote,
      `PBDB interval: ${record.interval} (${record.earlyAgeMa}-${record.lateAgeMa} Ma).`,
      `Fossil occurrence locality: ${record.locality}.`,
      `Formation/group: ${record.formation}.`,
      `PBDB ecology: diet ${record.diet}, habit ${record.lifeHabit}.`,
    ],
    habitat: `${record.formation} fossil occurrence, ${formatLocation(record)}`,
    population: `Extinct fossil taxon; PBDB occurrence ${record.pbdbOccurrenceId}`,
    wikiUrl: `https://en.wikipedia.org/wiki/${encodeURIComponent(record.commonName.replace(/ /g, '_'))}`,
    imageUrl: realImg || illustration.url,
    imageAlt: record.commonName,
    imageCredit: realImg ? 'Wikipedia / Wikimedia Commons' : illustration.credit,
    imageKind: realImg ? 'photo' : 'illustration',
    atlasMode: 'prehistoric',
    dinosaur: record,
    sourceUrl: record.sourceUrl,
  };
})
