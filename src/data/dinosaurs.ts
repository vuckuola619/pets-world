function titleCase(value: string): string {
  if (value === 'Not listed in PBDB') return value
  return value.replace(/\b\w/g, (letter) => letter.toUpperCase())
}

function formatLocation(record: DinosaurRecord): string {
  return record.state ? `${record.state}, ${record.country}` : record.country
}

function emojiFor(record: DinosaurRecord): string {
  return record.diet.toLowerCase().includes('carnivore') ? '🦖' : '🦕'
}

